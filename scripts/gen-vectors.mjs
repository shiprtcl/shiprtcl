// Generates conformance/fingerprint-vectors.json from the cases below using the reference
// implementation. Any conforming implementation MUST reproduce `canonical` and `fingerprint`.
import { writeFile } from 'node:fs/promises';
import { fingerprint, parse } from '../packages/shiprtcl/dist/index.js';

const many = Object.fromEntries(Array.from({ length: 257 }, (_, i) => [`k${i}`, i]));

const cases = [
  ['whitepaper-example', 'The worked example from the whitepaper §5.', 'application/json',
    '{"event":"payment_success","customer":{"email":"user@example.com","id":9812},"amount":49.50,"items":["sku_1","sku_2"]}'],
  ['value-independence', 'Same structure as whitepaper-example with different values and key order. MUST produce the same fingerprint.', 'application/json',
    '{"items":["x"],"amount":1,"customer":{"id":0,"email":""},"event":"refund"}'],
  ['integer-vs-float', 'Integers and floats are both NUM.', 'application/json', '{"a":1,"b":1.5,"c":-0,"d":1e21}'],
  ['empty-containers', 'Empty arrays and objects contribute only their own entry.', 'application/json', '{"list":[],"obj":{}}'],
  ['null-and-bool', 'NULL and BOOL markers.', 'application/json', '{"a":null,"b":true,"c":false}'],
  ['array-of-objects-union', 'Element shapes are unioned; keys present in only some elements still appear.', 'application/json',
    '{"items":[{"sku":"a","qty":1},{"sku":"b","note":"gift"}]}'],
  ['mixed-array', 'Type markers at one path are unioned and sorted.', 'application/json', '{"v":[1,"two",null,true,{"x":1},[2]]}'],
  ['nested-arrays', 'Wildcards nest.', 'application/json', '{"m":[[1,2],[3]]}'],
  ['map-numeric-keys', 'An object whose keys are all numeric is a MAP (rule 2).', 'application/json', '{"by_id":{"101":{"n":1},"102":{"n":2,"x":true}}}'],
  ['map-uuid-keys', 'UUID keys make a MAP.', 'application/json', '{"sessions":{"3f2b8a1e-9c4d-4b7a-8e2f-1a2b3c4d5e6f":1}}'],
  ['map-email-keys', 'Email keys make a MAP, so addresses never appear in shapes.', 'application/json', '{"scores":{"a@example.com":1,"b@example.org":2}}'],
  ['map-prefixed-id-keys', 'Prefixed opaque ids (letters, underscore, 8+ alphanumerics with a digit) make a MAP.', 'application/json', '{"prices":{"price_1NxYz2AbCdEf":{"unit":100}}}'],
  ['not-a-map', 'snake_case keys are not dynamic.', 'application/json', '{"meta":{"order_reference":"x","billing_address":"y"}}'],
  ['map-hint', 'A contract mapHint forces MAP regardless of keys.', 'application/json', '{"metadata":{"campaign":"x","utm_source":"y"}}', ['/metadata']],
  ['too-many-keys', 'More than 256 keys is always a MAP (rule 3).', 'application/json', JSON.stringify({ wide: many })],
  ['pointer-escaping', 'RFC 6901 escaping: "~" → "~0", "/" → "~1". Dots are ordinary characters.', 'application/json', '{"a/b":1,"c~d":2,"e.f":3,"~*":4}'],
  ['unicode-nfc', 'Keys are NFC-normalized: decomposed "e\\u0301" equals composed "\\u00e9".', 'application/json', '{"caf\\u0065\\u0301":1}'],
  ['code-point-order', 'Paths sort by Unicode code point, not UTF-16 code unit.', 'application/json', '{"\\uffff":1,"\\ud83d\\ude00":2,"z":3}'],
  ['root-array', 'A root array.', 'application/json', '[{"a":1}]'],
  ['root-scalar', 'A root scalar.', 'application/json', '"hello"'],
  ['csv', 'CSV: header row, every cell STR, root ARR.', 'text/csv', 'id,zip,amount\n1,01234,9.50\n2,"10001",3\n'],
  ['form-urlencoded', 'Form bodies: every value STR; key[] and repeated keys become ARR.', 'application/x-www-form-urlencoded', 'From=%2B15550001&Body=hi&MediaUrl[]=a&tag=x&tag=y'],
];

const vectors = [];
for (const [name, description, mediaType, body, mapHints] of cases) {
  const fp = await fingerprint(parse(body, mediaType), { mapHints });
  vectors.push({ name, description, mediaType, body, ...(mapHints ? { mapHints } : {}), canonical: fp.canonical, fingerprint: fp.id });
}

const doc = {
  $comment: 'SHIPRTCL v0.1 fingerprint conformance vectors. Generated by scripts/gen-vectors.mjs; do not edit by hand.',
  spec: 'https://shiprtcl.org/spec/#4-structural-fingerprint',
  version: '0.1',
  vectors,
};
await writeFile(new URL('../conformance/fingerprint-vectors.json', import.meta.url), JSON.stringify(doc, null, 2) + '\n');
console.log(`wrote ${vectors.length} vectors`);
